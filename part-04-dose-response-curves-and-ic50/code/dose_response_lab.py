import hashlib
import json
import math
from pathlib import Path
import platform
import sys
import time
from typing import Any

# NumPy does the array maths; it is the only third-party package this lab needs.
import numpy as np


# ROOT is the part folder (this file lives in code/, so go one level up). Data lives in ROOT/data.
ROOT = Path(__file__).resolve().parents[1]
# Fixed random seed: the synthetic wells and the bootstrap are exactly repeatable.
SEED = 20261114
# Nine test concentrations in nanomolar, spaced about 3-fold (a half-log series) from 0.1 to 1000 nM.
DOSES_NM = np.array([0.1, 0.3, 1, 3, 10, 30, 100, 300, 1000], dtype=float)
# Search limits for the fit: log10(midpoint in nM) from -3 to 6, and Hill slope from 0.3 to 3.
BOUNDS = ((-3.0, 6.0), (0.3, 3.0))


def json_bytes(value: Any) -> bytes:
    """Turn any JSON-friendly value into stable bytes: sorted keys, 2-space indent, trailing newline.

    Stable bytes mean the same data always gives the same file hash. NaN and infinity are refused
    (allow_nan=False) because they are not valid JSON.
    """
    return (json.dumps(value, indent=2, sort_keys=True, allow_nan=False) + "\n").encode()


def sha(path: Path) -> str:
    """Return the SHA-256 fingerprint of a file as hex text, to prove a file has not changed."""
    return hashlib.sha256(path.read_bytes()).hexdigest()


def hill(concentration_nm: Any, midpoint_nm: float, slope: float,
         bottom: float = 0.0, top: float = 100.0) -> np.ndarray:
    """Hill (log-logistic) curve: percent response at each concentration.

    response = bottom + (top - bottom) / (1 + (midpoint / concentration) ** slope)
    At concentration == midpoint the curve sits exactly halfway between bottom and top. A larger
    slope makes the rise steeper. Zero concentration is allowed (response = bottom).
    """
    # Accept lists, numbers or arrays, and refuse anything that is not a sensible physical curve.
    x = np.asarray(concentration_nm, dtype=float)
    if np.any(~np.isfinite(x)) or np.any(x < 0) or midpoint_nm <= 0 or slope <= 0 or top <= bottom:
        raise ValueError("positive midpoint/slope, ordered plateaus and nonnegative finite doses required")
    # The Hill equation. np.maximum avoids dividing by exactly zero when the concentration is 0.
    return bottom + (top - bottom) / (1 + (midpoint_nm / np.maximum(x, 1e-300)) ** slope)


def normalize(signal: Any, vehicle: float, inhibited: float) -> np.ndarray:
    """Convert raw signal to percent inhibition for an assay where LOWER signal means MORE inhibition.

    0 percent = the vehicle (no-drug) signal, 100 percent = the inhibited reference signal.
    Results outside 0-100 are returned as they are, so noise and QC problems stay visible.
    """
    if not np.isfinite([vehicle, inhibited]).all() or vehicle <= inhibited:
        raise ValueError("this falling-signal assay requires vehicle > inhibited reference")
    # Every signal must be a finite number before it is normalized.
    values = np.asarray(signal, dtype=float)
    if not np.isfinite(values).all():
        raise ValueError("signals must be finite")
    # Values outside 0–100 remain visible: silently clipping would hide noise/QC.
    return 100 * (vehicle - values) / (vehicle - inhibited)


def pic50(value: float, unit: str = "nM") -> float:
    """Convert an IC50 concentration to pIC50 = -log10(IC50 in molar). 10 nM gives 8.

    The unit must be a known molar unit, and the value must be positive and finite.
    """
    # Multiplier that turns each supported unit into molar (M).
    factors = {"M": 1.0, "mM": 1e-3, "uM": 1e-6, "nM": 1e-9, "pM": 1e-12}
    if unit not in factors or not math.isfinite(value) or value <= 0:
        raise ValueError("pIC50 requires a positive finite concentration and supported molar unit")
    # pIC50 = -log10(IC50 in molar).
    return -math.log10(value * factors[unit])


def absolute_crossing(midpoint_nm: float, slope: float, bottom: float, top: float,
                      response: float = 50.0) -> float | None:
    """Concentration where the curve reaches exactly `response` percent (default 50), or None.

    If the top plateau never reaches that level (or the bottom is already above it), no absolute
    crossing exists and None is returned. This is why a 'relative' midpoint and an 'absolute' IC50
    can differ when plateaus are not 0 and 100.
    """
    # A level outside the plateaus can never be reached by this curve.
    if not bottom < response < top:
        return None
    # Solve the Hill equation for the concentration at the requested response.
    return midpoint_nm * ((response - bottom) / (top - response)) ** (1 / slope)


def fit_hill(doses_nm: Any, inhibition: Any) -> dict[str, Any]:
    """Bounded coarse-to-fine least squares, plateaus fixed at 0 and 100.

    Log10(midpoint/nM) and slope use a 41x41 grid, then seven deterministic
    refinements. This small explicit optimizer is for teaching, not a validated
    production replacement for nonlinear-regression software.

    Returns a dictionary with a `status`:
      accepted_for_teaching ........ passed every teaching QC check
      flagged_do_not_report_as_validated_ic50 .. a QC check failed (see `reasons`)
      refused ...................... 50 percent inhibition is not bracketed by the data
    """
    # Step 1 of fit_hill: check the inputs. Bad inputs raise an error rather than produce a number.
    doses, values = np.asarray(doses_nm, dtype=float), np.asarray(inhibition, dtype=float)
    if doses.ndim != 1 or values.shape != doses.shape or len(doses) < 5:
        raise ValueError("need matching one-dimensional arrays with at least five concentrations")
    if not np.isfinite(doses).all() or not np.isfinite(values).all() or np.any(doses <= 0):
        raise ValueError("fit uses finite positive doses; zero-dose controls are separate")
    if len(np.unique(doses)) != len(doses):
        raise ValueError("aggregate technical wells to one mean per concentration first")
    if not np.all(np.diff(doses) > 0):
        raise ValueError("concentrations must be strictly increasing")
    # Reference error: how badly a flat line at the mean would fit. A useful fit must beat this by far.
    baseline = float(np.mean((values - values.mean()) ** 2))
    # Refuse a precise IC50 unless the data actually cross 50 percent inside the tested range.
    if not values.min() < 50 < values.max():
        return {"status": "refused", "reasons": ["absolute 50% inhibition is not bracketed by observed concentration means"],
                "direction": "if a monotone 50% crossing exists: > highest tested concentration" if values.max() < 50 else "if a monotone 50% crossing exists: < lowest tested concentration",
                "absolute_ic50_nm": None, "rmse_constant_baseline": math.sqrt(baseline)}
    # Step 2: coarse-to-fine grid search. Start with the full parameter box...
    low, high = np.array([b[0] for b in BOUNDS]), np.array([b[1] for b in BOUNDS])
    logx = np.log10(doses)
    # ...evaluate a 41 x 41 grid of (midpoint, slope), keep the best cell, then zoom the box around it. Eight rounds.
    for _ in range(8):
        logs = np.linspace(low[0], high[0], 41)
        slopes = np.linspace(low[1], high[1], 41)
        # Predicted inhibition for every grid cell at every concentration (a 3-D array: midpoint x slope x dose).
        prediction = 100 / (1 + 10 ** ((logs[:, None, None] - logx[None, None, :]) * slopes[None, :, None]))
        # Mean squared error between prediction and observed means, for every grid cell.
        loss = np.mean((prediction - values) ** 2, axis=2)
        # Pick the grid cell with the smallest error.
        index = np.unravel_index(int(np.argmin(loss)), loss.shape)
        best = np.array([logs[index[0]], slopes[index[1]]])
        # One grid step becomes the half-width of the next, smaller search box (kept inside the global bounds).
        step = (high - low) / 40
        low = np.maximum([b[0] for b in BOUNDS], best - step)
        high = np.minimum([b[1] for b in BOUNDS], best + step)
    # Step 3: turn the best log10 midpoint back into nanomolar and report the fitted curve.
    midpoint = float(10 ** best[0])
    slope = float(best[1])
    predicted = hill(doses, midpoint, slope)
    residual = values - predicted
    rmse = float(np.sqrt(np.mean(residual ** 2)))
    # Step 4: QC checks. Each failed check adds a plain-language reason.
    reasons = []
    # A result sitting on a search limit means the optimizer was cornered, not that it found the answer.
    if any(abs(best[i] - edge) < 1e-5 for i, bounds in enumerate(BOUNDS) for edge in bounds):
        reasons.append("optimizer reached an imposed parameter bound")
    # Teaching threshold: the curve must follow the mean points within 5 percentage points.
    if rmse > 5:
        reasons.append("mean-point RMSE exceeds teaching QC threshold of 5 percentage points")
    # The fixed 0/100 plateaus are only believable if the lowest dose is near 0 and the highest is near 100.
    if values[0] > 10 or values[-1] < 90:
        reasons.append("observed endpoints do not support the fixed 0/100 plateau teaching assumption")
    # A big dip in the middle of the series means a single sigmoid is the wrong model.
    if np.any(np.diff(values) < -10):
        reasons.append("large nonmonotonic decrease exceeds teaching QC threshold of 10 percentage points")
    # Package the result. The absolute IC50 and pIC50 are only filled in if every check passed.
    return {"status": "accepted_for_teaching" if not reasons else "flagged_do_not_report_as_validated_ic50",
            "reasons": reasons, "relative_midpoint_nm": midpoint,
            "absolute_ic50_nm": midpoint if not reasons else None,
            "pIC50": pic50(midpoint) if not reasons else None, "hill_slope": slope,
            "fixed_bottom_percent": 0, "fixed_top_percent": 100,
            "rmse_percentage_points": rmse, "rmse_constant_baseline": math.sqrt(baseline),
            "mean_squared_error": float(np.mean(residual ** 2)),
            "prediction_percent": predicted.tolist(), "residual_percent": residual.tolist(),
            "bounds_log10_midpoint_nm_and_slope": BOUNDS,
            "assumption": "single increasing sigmoid; plateaus fixed to 0 and 100, supported only by this synthetic design"}


def synthetic_data() -> tuple[list[dict[str, Any]], np.ndarray]:
    """Build the fake plate: 9 concentrations x 3 technical wells plus control wells.

    Returns (rows, wells): the row-per-well table that is saved as CSV, and the 9x3 array of
    percent inhibition after normalization. The seed is fixed, so every run is identical.
    """
    # A seeded random generator, so the 'plate' is the same on every run.
    rng = np.random.default_rng(SEED)
    # The hidden truth: midpoint 10 nM, slope 1. The fit should recover it approximately.
    true_inhibition = hill(DOSES_NM, 10, 1)
    # Signal falls from 1000 (no inhibition) to 100 (full inhibition), plus Gaussian noise (SD 12) per well.
    signals = 1000 - 900 * true_inhibition[:, None] / 100 + rng.normal(0, 12, (len(DOSES_NM), 3))
    # One table row per test well, clearly labelled as synthetic.
    rows = [{"dataset": "SYNTHETIC teaching wells; not observed biology", "well_kind": "test",
             "concentration_nm": float(dose), "technical_well": j + 1, "signal_arbitrary_units": float(signals[i, j])}
            for i, dose in enumerate(DOSES_NM) for j in range(3)]
    # Add control wells: vehicle (no drug, concentration 0) and the fully inhibited reference.
    for kind, values in [("vehicle", [1001, 998, 1001]), ("inhibited_reference", [101, 98, 101])]:
        rows += [{"dataset": "SYNTHETIC teaching wells; not observed biology", "well_kind": kind,
                  "concentration_nm": 0 if kind == "vehicle" else None, "technical_well": j + 1,
                  "signal_arbitrary_units": value} for j, value in enumerate(values)]
    # Normalize with the control means (1000 and 100) and return both the table and the percent-inhibition array.
    return rows, normalize(signals, 1000, 100)


def bootstrap(doses: np.ndarray, wells: np.ndarray, count: int = 400) -> dict[str, Any]:
    """Estimate how much the fit moves if technical wells are resampled.

    For each resample, wells at every concentration are drawn with replacement, averaged and refit.
    Only fits that pass the QC checks are counted. If fewer than 90 percent pass, no interval is
    reported. This measures technical-well noise only, not biological variation.
    """
    # A different but fixed seed for the bootstrap, so it does not reuse the data noise.
    rng = np.random.default_rng(SEED + 1)
    estimates = []
    for _ in range(count):
        # Choose, for each concentration, three wells at random with replacement.
        indices = rng.integers(0, wells.shape[1], size=wells.shape)
        # Average the resampled wells at each concentration, then refit the curve.
        means = np.take_along_axis(wells, indices, axis=1).mean(axis=1)
        fit = fit_hill(doses, means)
        if fit["status"] == "accepted_for_teaching":
            estimates.append(fit["absolute_ic50_nm"])
    # Too many failed refits would make an interval misleading, so stop instead.
    if len(estimates) < 0.9 * count:
        raise ValueError("too many failed bootstrap fits; do not summarize a selective interval")
    # Report the 2.5th and 97.5th percentiles as a 95 percent interval, with its limited scope spelled out.
    return {"resamples": count, "accepted": len(estimates), "seed": SEED + 1,
            "percentile_95_interval_nm": np.percentile(estimates, [2.5, 97.5]).tolist(),
            "scope": "within-concentration technical-well resampling, conditional on fixed controls, synthetic design and 0/100 model; not biological uncertainty",
            "estimates_nm": estimates}


def validate_prerequisite(manifest: dict[str, Any]) -> None:
    """Stop early if the Part 3 manifest is not the exact EGFR / erlotinib identity this lab expects.

    Checks the schema version, the UniProt accession and isoform, the ChEMBL target ID, and the
    ChEMBL compound ID plus InChIKey of erlotinib.
    """
    if manifest.get("schema_version") != "1.0.0" or manifest.get("artifact_id") != "wb.add.episode03.target-compound-manifest.v1":
        raise ValueError("unsupported episode 3 prerequisite schema/identity")
    # Find the EGFR target record in the Part 3 manifest.
    egfr = next(t for t in manifest["targets"] if t["gene"] == "EGFR")
    # Find the erlotinib compound record.
    erlotinib = next(c for c in manifest["reference_compounds"] if c["teaching_name"] == "erlotinib")
    # EGFR must be the human reference isoform P00533-1, ChEMBL target CHEMBL203.
    if (egfr["reference_sequence"]["uniprot_accession"], egfr["reference_sequence"]["isoform_id"], egfr["variant"], egfr["chembl_target_id"]) != ("P00533", "P00533-1", "reference", "CHEMBL203"):
        raise ValueError("EGFR prerequisite identity differs")
    # Erlotinib must be exactly CHEMBL553 with the expected InChIKey, not a salt or look-alike.
    if (erlotinib["chembl_id_exact_component_match"], erlotinib["standard_inchi_key"]) != ("CHEMBL553", "AAKJLRGGTJKAMG-UHFFFAOYSA-N"):
        raise ValueError("erlotinib exact identity differs")


def main() -> None:
    """Run the whole lab: check inputs, make data, fit, bootstrap, write outputs, print a summary."""
    # Start a timer for the run receipt.
    start = time.perf_counter()
    # Outputs go to data/outputs (created if missing); inputs come from data/raw.
    out = ROOT / "data/outputs"
    out.mkdir(parents=True, exist_ok=True)
    raw = ROOT / "data/raw"
    prerequisite = raw / "episode03-target_reference_manifest.v1.json"
    # Step 1: read and validate the saved Part 3 result before doing anything else.
    manifest = json.loads(prerequisite.read_text())
    validate_prerequisite(manifest)
    source_identity = json.loads((raw / "PREREQUISITE_IDENTITY.json").read_text())
    # The manifest bytes must match the hash saved next to it, so a silent edit is caught.
    if sha(prerequisite) != source_identity["sha256"]:
        raise ValueError("prerequisite bytes differ from the retained snapshot identity")
    # Step 2: make the synthetic plate and save it as a CSV.
    rows, wells = synthetic_data()
    with (out / "synthetic_wells.csv").open("w", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=list(rows[0]))
        writer.writeheader(); writer.writerows(rows)
    # Step 3: average the three wells at each concentration, then fit and bootstrap.
    means = wells.mean(axis=1)
    fit = fit_hill(DOSES_NM, means)
    uncertainty = bootstrap(DOSES_NM, wells)
    # Step 4: the lesson's failure cases, each one a situation where a careless fit would lie.
    cases = {
        "unbracketed_low_range": fit_hill(DOSES_NM[:5], means[:5] - 5),
        "bad_nonmonotonic_model": fit_hill(DOSES_NM, [1, 2, 3, 5, 80, 20, 95, 50, 98]),
        "incomplete_plateau": {"bottom_percent": 0, "top_percent": 40, "relative_midpoint_nm": 10,
                               "hill_slope": 1, "response_at_relative_midpoint_percent": 20,
                               "absolute_50_percent_crossing_nm": absolute_crossing(10, 1, 0, 40),
                               "interpretation": "a relative half-dynamic-range midpoint exists; absolute 50% inhibition is never reached"},
        "different_relative_and_absolute": {"bottom_percent": 10, "top_percent": 70, "relative_midpoint_nm": 100,
                                            "hill_slope": 1, "response_at_relative_midpoint_percent": 40,
                                            "absolute_50_percent_crossing_nm": absolute_crossing(100, 1, 10, 70)},
    }
    # Step 5: gather everything into one lesson payload, with limits written down.
    payload = {"artifact_id": "wb.add.episode04.synthetic-dose-response.v1", "schema_version": "1.0.0",
               "producer_episode": 4, "measured_versus_synthetic": "synthetic; NOT observed erlotinib/EGFR activity",
               "seed": SEED, "true_model": {"midpoint_nm": 10, "hill_slope": 1, "bottom_percent": 0, "top_percent": 100},
               "normalization": {"vehicle_mean": 1000, "inhibited_reference_mean": 100,
                                 "worked_sample_signal": 550, "worked_inhibition_percent": 50,
                                 "formula": "100*(vehicle-sample)/(vehicle-inhibited_reference)",
                                 "signal_direction": "lower signal means more inhibition; assay-specific"},
               "doses_nm": DOSES_NM.tolist(), "technical_inhibition_percent": wells.tolist(),
               "means_percent": means.tolist(), "sample_sd_percent": wells.std(axis=1, ddof=1).tolist(),
               "fit": fit, "uncertainty": uncertainty, "failure_cases": cases,
               "ideal_worked_model": {"midpoint_nm": 10, "hill_slope": 1,
                                      "doses_nm": [1, 10, 100], "inhibition_percent": hill([1, 10, 100], 10, 1).tolist()},
               "unit_examples": [{"IC50_nm": n, "pIC50": pic50(n)} for n in [1, 10, 100, 1000]],
               "prerequisite": source_identity,
               "limits": ["No biological replication, inference, validation, toxicity, selectivity or clinical claim",
                          "Fixed 0/100 plateaus are a teaching assumption; inspect real assay plateaus and methods",
                          "QC thresholds are disclosed teaching checks, not validated universal acceptance criteria",
                          "Zero-dose controls normalize signals and are never logged or placed at a fake positive dose"]}
    # Save the payload, the fit and the failure cases as three JSON files.
    for name, data in [("lesson_payload.json", payload), ("fit_results.json", fit), ("qc_cases.json", cases)]:
        (out / name).write_bytes(json_bytes(data))
    # Step 6: a run receipt (time, versions, hashes of this script and of every output).
    receipt = {"generated_utc": datetime.now(timezone.utc).isoformat(), "python": sys.version,
               "numpy": np.__version__, "platform": platform.platform(), "processor": platform.machine(),
               "elapsed_seconds": time.perf_counter() - start, "seed": SEED,
               "command": "Tools/ssd-run.sh python Playlists/ai-in-drug-discovery/4/code/dose_response_lab.py",
               "network_calls": 0, "new_dependencies": 0, "paid_services": 0,
               "code_sha256": sha(Path(__file__)), "prerequisite_sha256": sha(prerequisite),
               "outputs": {p.name: sha(p) for p in sorted(out.iterdir()) if p.name in {"synthetic_wells.csv", "lesson_payload.json", "fit_results.json", "qc_cases.json"}}}
    (out / "run_receipt.json").write_bytes(json_bytes(receipt))
    # Print a short summary to the screen.
    print(json.dumps({"synthetic_only": True, "concentrations": len(DOSES_NM), "technical_wells": wells.size,
                      "fit": fit, "bootstrap_95_interval_nm": uncertainty["percentile_95_interval_nm"],
                      "bootstrap_accepted": uncertainty["accepted"], "elapsed_seconds": receipt["elapsed_seconds"]}, indent=2))


if __name__ == "__main__":
    main()
