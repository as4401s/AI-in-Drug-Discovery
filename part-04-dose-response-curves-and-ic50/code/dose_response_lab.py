"""Dose-response curves and IC50: a small, honest fitting lab
(Part 4: "Dose-Response Curves and IC50")

This is a teaching script. It uses SYNTHETIC wells (numbers generated by a random-number
generator), so the curve it fits is NOT a real experiment and NOT a measured erlotinib/EGFR result.
Real measured records are handled by the sibling script curate_activities.py.

WHAT THIS SCRIPT DOES, STEP BY STEP
  1. Checks that the saved result of Part 3 (the target and compound manifest) is unchanged.
  2. Makes nine concentrations x three technical wells of fake plate-reader signal around a known
     curve (midpoint 10 nM, Hill slope 1), plus vehicle and inhibited-reference control wells.
  3. Normalizes signal to percent inhibition: 100 * (vehicle - sample) / (vehicle - inhibited reference).
     Values outside 0-100 are kept, never clipped, so noise stays visible.
  4. Fits a Hill curve with two free numbers (midpoint and slope) and both plateaus fixed at 0 and 100
     percent, using a small explicit coarse-to-fine search (no SciPy needed, so every step can be read).
  5. Refuses or flags fits that should not be reported: 50 percent not bracketed, large non-monotonic
     dips, an optimizer stuck on a bound, a poor RMSE, or end points that do not support the plateaus.
  6. Bootstraps the technical wells (400 resamples, fixed seed) for a 95 percent interval.
  7. Shows the failure cases of the lesson: unbracketed range, bad model, incomplete plateau, and
     relative midpoint versus absolute 50 percent crossing.
  8. Writes JSON and CSV files and a run receipt into data/outputs/.

WHAT YOU NEED
  * Python 3.10 or newer and NumPy. No network access and no other packages.
  * The folder layout of this repository: code/ next to data/ (data/raw holds the Part 3 result).

HOW TO RUN IT
  python code/dose_response_lab.py
  python -m unittest discover -s code -p "test_dose_response_lab.py"     (the offline checks)

WHAT YOU SHOULD SEE (values from the run shown in the video)
  fit status ............ accepted_for_teaching
  IC50 (midpoint) ....... about 9.78 nM, so pIC50 about 8.01
  Hill slope ............ about 1.00
  RMSE of the fit ....... about 0.45 percentage points (a flat baseline would score about 39)
  bootstrap 95% interval  about 9.3 to 10.3 nM (all 400 resamples accepted)
  The saved run_receipt.json lists the SHA-256 hash of this file and of every output.

HOW TO READ THE RESULT
  The interval only describes how much technical-well noise moves the fit. It is not biological
  uncertainty, and the fixed 0/100 plateaus are a teaching assumption. Do not quote a synthetic
  IC50 as if it were a measurement.
"""

# Postponed evaluation of type hints keeps the annotations below cheap and readable.
from __future__ import annotations

# Standard library first: csv for tables, datetime/platform/sys/time for the run receipt, hashlib for file hashes.
import csv
